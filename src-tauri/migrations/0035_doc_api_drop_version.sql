-- показывалась: карточка «Version» на обзорной странице да поля в двух формах.
-- Ни на сборку URL, ни на выбор эндпоинта, ни на импорт-экспорт она не влияла —
-- версионирование API живёт в префиксе (`/v1`), который и подставляется в
-- запрос. Хранить рядом вторую, ни с чем не сверяемую строку значит показывать
-- «1.0.0» из шаблона диалога создания как факт о документе.
--
-- Файлы импорта старого формата с полем `version` читаются по-прежнему: лишний
-- ключ заголовка просто не доезжает до бэкенда.
ALTER TABLE doc_api DROP COLUMN version;
