-- Область на ERD-холсте: подписанный прямоугольник, которым таблицы
-- группируются по смыслу (подсистема, схема БД, ограниченный контекст).
--
-- Состав области нигде не хранится: ей принадлежат те таблицы, что лежат
-- внутри её прямоугольника. Колонка `frame_id` у сущности означала бы второй
-- источник правды о том же самом — и он рано или поздно разошёлся бы с
-- картинкой, потому что таблицу двигают, а не «перекладывают в группу».
CREATE TABLE erd_frame (
    id         TEXT PRIMARY KEY,
    -- Диаграмма, которой принадлежит область. Удаление диаграммы уносит её
    -- области так же, как и таблицы (0036).
    doc_erd_id TEXT NOT NULL REFERENCES doc_erd(id) ON DELETE CASCADE,
    title      TEXT NOT NULL DEFAULT '',
    -- Прямоугольник в мировых координатах сцены — тех же, в которых лежат
    -- `entities.pos_x` / `pos_y` (0033).
    x          REAL NOT NULL,
    y          REAL NOT NULL,
    w          REAL NOT NULL,
    h          REAL NOT NULL
);

CREATE INDEX idx_erd_frame_doc_erd_id ON erd_frame (doc_erd_id);
