/// Хранилище тел документов — markdown-текста, привязанного к узлу дерева.
/// Обслуживает два вида узлов: обзорную часть doc-api и markdown-документ.
///
/// Тела лежат отдельными файлами `<node_id>.md` вне какого-либо пользовательского
/// дерева файлов: имя и место документа задаёт узел, поэтому переименование и
/// перенос не трогают диск вовсе.
pub trait ContentRepository {
    /// Тело документа или пустая строка, если его ещё нет — редактор должен
    /// открывать только что созданный документ без ошибки.
    async fn read(&self, node_id: &str) -> Result<String, String>;
    async fn write(&self, node_id: &str, content: &str) -> Result<(), String>;
    async fn delete(&self, node_id: &str) -> Result<(), String>;
}
