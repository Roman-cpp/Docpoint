import type { Param } from "@/entities/doc-api";

/**
 * Параметр глазами документации: то, что модель хранит сегодня, плюс поля,
 * которые ей ещё предстоит завести, чтобы не отставать от OpenAPI.
 *
 * Все добавленные поля необязательные, и страница рисует каждое только когда
 * оно пришло. Поэтому блок параметров уже умеет их показывать: как только
 * поле появится в `Param` и доедет с бэкенда, в строке само собой загорится
 * ещё одна метка — верстать заново ничего не придётся.
 */
export interface DocParam extends Param {
	/** `uuid`, `email`, `date-time` — уточнение типа из OpenAPI `format`. */
	format?: string;
	/** Закрытый список допустимых значений (`enum`). */
	enumValues?: string[];
	/** Пример значения — то же, что `example` у поля ответа. */
	example?: string;
	/** Значение может быть `null` — отдельно от «необязательный». */
	nullable?: boolean;
	/** Параметр доживает последние версии и скоро исчезнет. */
	deprecated?: boolean;
	/** Ограничения строкой: `1…100`, `^\\d{4}$`, `не длиннее 64`. */
	constraints?: string[];
}
