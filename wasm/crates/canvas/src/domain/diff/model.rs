//! Метка «откуда известна эта таблица, колонка или связь»: результат сравнения
//! диаграммы с живой базой.
//!
//! Сцена её только рисует. Считает сравнение бэкенд (`compare_erd_with_db`), а
//! холст получает готовый ответ и раскрашивает по нему объединение. Вне режима
//! сравнения всё `Same`, и картинка остаётся обычной.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DiffStatus {
    /// Есть и в документе, и в базе, описание сходится.
    Same,
    /// Описано на диаграмме, но в базе не найдено.
    OnlyInDoc,
    /// Есть в базе, но на диаграмме не описано.
    OnlyInDb,
    /// Есть с обеих сторон, но описания расходятся.
    Differs,
}

impl DiffStatus {
    /// Разбор строки из ответа команды. Незнакомое значение — `Same`: красить
    /// наугад хуже, чем не красить вовсе.
    pub fn from_wire(raw: &str) -> DiffStatus {
        match raw {
            "onlyInDoc" => DiffStatus::OnlyInDoc,
            "onlyInDb" => DiffStatus::OnlyInDb,
            "differs" => DiffStatus::Differs,
            _ => DiffStatus::Same,
        }
    }
}
